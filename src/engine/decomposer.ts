import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { XmlEngine } from '../parser/xml-engine.js';
import { LoadedProfile } from '../parser/profile-reader.js';
import {
  ProfileMetadata,
  PermissionSetMetadata,
  PermissionSetGroupMetadata,
  ObjectPermission,
  FieldPermission,
  UserPermission,
  ClassAccess,
  PageAccess,
  CustomPermission,
  TabSetting,
  RecordTypeVisibility,
  ApplicationVisibility,
} from '../types/metadata.js';
import {
  DecomposeOptions,
  DecompositionResult,
  GeneratedPermissionSet,
  GeneratedPermissionSetGroup,
} from '../types/decomposition.js';

export class ProfileDecomposer {
  private xmlEngine: XmlEngine;

  constructor(xmlEngine?: XmlEngine) {
    this.xmlEngine = xmlEngine || new XmlEngine();
  }

  /**
   * Decompose a profile into modular Permission Sets and a Permission Set Group.
   */
  public async decompose(
    loadedProfile: LoadedProfile,
    options: DecomposeOptions
  ): Promise<DecompositionResult> {
    const strategy = options.strategy || 'by-domain';
    const prefix = options.prefix || `${loadedProfile.name}_`;
    const meta = loadedProfile.metadata;

    const generatedPermSets: GeneratedPermissionSet[] = [];

    if (strategy === 'consolidated') {
      // 1 single consolidated permission set
      const ps = this.createConsolidatedPermSet(loadedProfile, prefix, options.includeLicense);
      generatedPermSets.push(ps);
    } else {
      // Modular decomposition
      // 1. SObject & Field modular permission sets
      const sobjectPermSets = this.createSObjectPermSets(loadedProfile, prefix, strategy, options.includeLicense);
      generatedPermSets.push(...sobjectPermSets);

      // 2. User / System permissions
      const adminPermSet = this.createAdminPermSet(loadedProfile, prefix, options.includeLicense);
      if (adminPermSet) {
        generatedPermSets.push(adminPermSet);
      }

      // 3. Apex Class & Visualforce Page accesses
      const codePermSet = this.createCodePermSet(loadedProfile, prefix, options.includeLicense);
      if (codePermSet) {
        generatedPermSets.push(codePermSet);
      }

      // 4. Custom permissions
      const customPermSet = this.createCustomPermSet(loadedProfile, prefix, options.includeLicense);
      if (customPermSet) {
        generatedPermSets.push(customPermSet);
      }
    }

    // Generate Permission Set Group if requested (default: true)
    let psg: GeneratedPermissionSetGroup | undefined;
    if (options.createGroup !== false && generatedPermSets.length > 0) {
      const psgApiName = options.groupName || `${loadedProfile.name}_PSG`;
      const psgMetadata: PermissionSetGroupMetadata = {
        label: `${this.formatLabel(loadedProfile.name)} Group`,
        description: `Permission Set Group replacing legacy profile: ${loadedProfile.name}. Generated by PermForge.`,
        hasActivationRequired: false,
        status: 'Updated',
        permissionSets: generatedPermSets.map((ps) => ps.apiName),
      };

      psg = {
        apiName: psgApiName,
        fileName: `${psgApiName}.permissionsetgroup-meta.xml`,
        metadata: psgMetadata,
      };
    }

    // Write outputs to target directories
    await this.writeOutputs(options.outputDir, generatedPermSets, psg);

    // Compute stats
    let totalObjectsCovered = 0;
    let totalFieldsCovered = 0;
    let totalUserPermsCovered = 0;
    let totalApexCovered = 0;

    for (const ps of generatedPermSets) {
      totalObjectsCovered += ps.metadata.objectPermissions?.length || 0;
      totalFieldsCovered += ps.metadata.fieldPermissions?.length || 0;
      totalUserPermsCovered += ps.metadata.userPermissions?.length || 0;
      totalApexCovered += ps.metadata.classAccesses?.length || 0;
    }

    return {
      sourceProfile: loadedProfile.name,
      strategy,
      permissionSets: generatedPermSets,
      permissionSetGroup: psg,
      stats: {
        totalPermissionSets: generatedPermSets.length,
        totalObjectsCovered,
        totalFieldsCovered,
        totalUserPermissionsCovered: totalUserPermsCovered,
        totalApexClassesCovered: totalApexCovered,
      },
    };
  }

  private createConsolidatedPermSet(
    profile: LoadedProfile,
    prefix: string,
    includeLicense?: boolean
  ): GeneratedPermissionSet {
    const meta = profile.metadata;
    const apiName = `${prefix}Full`;

    const activeObj = (meta.objectPermissions || []).filter(
      (o) => o.allowCreate || o.allowRead || o.allowEdit || o.allowDelete || o.viewAllRecords || o.modifyAllRecords
    );
    const activeField = (meta.fieldPermissions || []).filter((f) => f.readable || f.editable);
    const activeUser = (meta.userPermissions || []).filter((u) => u.enabled);
    const activeClass = (meta.classAccesses || []).filter((c) => c.enabled);
    const activePage = (meta.pageAccesses || []).filter((p) => p.enabled);
    const activeCustom = (meta.customPermissions || []).filter((c) => c.enabled);

    const tabSettings: TabSetting[] = (meta.tabVisibilities || [])
      .filter((t) => t.visibility === 'DefaultOn' || t.visibility === 'DefaultOff')
      .map((t) => ({
        tab: t.tab,
        visibility: 'Visible',
      }));

    const permSetMeta: PermissionSetMetadata = {
      label: `${this.formatLabel(profile.name)} (Full Permissions)`,
      description: `Consolidated permission set generated from profile ${profile.name} by PermForge.`,
      hasActivationRequired: false,
      license: includeLicense ? profile.metadata.userLicense : undefined,
      objectPermissions: activeObj.length > 0 ? activeObj : undefined,
      fieldPermissions: activeField.length > 0 ? activeField : undefined,
      userPermissions: activeUser.length > 0 ? activeUser : undefined,
      classAccesses: activeClass.length > 0 ? activeClass : undefined,
      pageAccesses: activePage.length > 0 ? activePage : undefined,
      customPermissions: activeCustom.length > 0 ? activeCustom : undefined,
      tabSettings: tabSettings.length > 0 ? tabSettings : undefined,
      recordTypeVisibilities: meta.recordTypeVisibilities,
      applicationVisibilities: meta.applicationVisibilities,
    };

    return {
      apiName,
      fileName: `${apiName}.permissionset-meta.xml`,
      metadata: permSetMeta,
      category: 'base',
    };
  }

  private createSObjectPermSets(
    profile: LoadedProfile,
    prefix: string,
    strategy: 'by-domain' | 'by-object' | 'tiered',
    includeLicense?: boolean
  ): GeneratedPermissionSet[] {
    const meta = profile.metadata;
    const activeObj = (meta.objectPermissions || []).filter(
      (o) => o.allowCreate || o.allowRead || o.allowEdit || o.allowDelete || o.viewAllRecords || o.modifyAllRecords
    );
    const activeField = (meta.fieldPermissions || []).filter((f) => f.readable || f.editable);

    // Grouping mapping: key -> { objects: ObjectPermission[], fields: FieldPermission[] }
    const groups = new Map<
      string,
      {
        objects: ObjectPermission[];
        fields: FieldPermission[];
        recordTypes: RecordTypeVisibility[];
        tabs: TabSetting[];
      }
    >();

    const getGroupKey = (sobjectName: string): string => {
      if (strategy === 'by-object') {
        return sobjectName.replace(/__c$/, '');
      }
      return this.mapToDomain(sobjectName);
    };

    // Populate objects
    for (const obj of activeObj) {
      const key = getGroupKey(obj.object);
      if (!groups.has(key)) {
        groups.set(key, { objects: [], fields: [], recordTypes: [], tabs: [] });
      }
      groups.get(key)!.objects.push(obj);
    }

    // Populate fields
    for (const field of activeField) {
      const sobject = field.field.split('.')[0];
      const key = getGroupKey(sobject);
      if (!groups.has(key)) {
        groups.set(key, { objects: [], fields: [], recordTypes: [], tabs: [] });
      }
      groups.get(key)!.fields.push(field);
    }

    // Map tabs
    for (const tab of meta.tabVisibilities || []) {
      if (tab.visibility === 'DefaultOn' || tab.visibility === 'DefaultOff') {
        // Tab names often match standard-Account or CustomObject__c
        const sobjectCandidate = tab.tab.replace(/^standard-/, '');
        const key = getGroupKey(sobjectCandidate);
        if (groups.has(key)) {
          groups.get(key)!.tabs.push({
            tab: tab.tab,
            visibility: 'Visible',
          });
        }
      }
    }

    // Map Record Types
    for (const rt of meta.recordTypeVisibilities || []) {
      if (rt.visible) {
        const sobjectCandidate = rt.recordType.split('.')[0];
        const key = getGroupKey(sobjectCandidate);
        if (groups.has(key)) {
          groups.get(key)!.recordTypes.push(rt);
        }
      }
    }

    const results: GeneratedPermissionSet[] = [];

    for (const [groupKey, data] of groups.entries()) {
      if (data.objects.length === 0 && data.fields.length === 0) continue;

      const apiName = `${prefix}${groupKey}`;
      const permSetMeta: PermissionSetMetadata = {
        label: `${this.formatLabel(profile.name)} - ${this.formatLabel(groupKey)}`,
        description: `Object and field security for ${groupKey}, migrated from ${profile.name} by PermForge.`,
        hasActivationRequired: false,
        license: includeLicense ? profile.metadata.userLicense : undefined,
        objectPermissions: data.objects.length > 0 ? data.objects : undefined,
        fieldPermissions: data.fields.length > 0 ? data.fields : undefined,
        tabSettings: data.tabs.length > 0 ? data.tabs : undefined,
        recordTypeVisibilities: data.recordTypes.length > 0 ? data.recordTypes : undefined,
      };

      results.push({
        apiName,
        fileName: `${apiName}.permissionset-meta.xml`,
        metadata: permSetMeta,
        category: 'domain',
      });
    }

    return results;
  }

  private createAdminPermSet(
    profile: LoadedProfile,
    prefix: string,
    includeLicense?: boolean
  ): GeneratedPermissionSet | null {
    const meta = profile.metadata;
    const activeUser = (meta.userPermissions || []).filter((u) => u.enabled);
    if (activeUser.length === 0) return null;

    const apiName = `${prefix}System_Permissions`;
    const permSetMeta: PermissionSetMetadata = {
      label: `${this.formatLabel(profile.name)} - System Permissions`,
      description: `Administrative and user permissions migrated from profile ${profile.name} by PermForge.`,
      hasActivationRequired: false,
      license: includeLicense ? profile.metadata.userLicense : undefined,
      userPermissions: activeUser,
    };

    return {
      apiName,
      fileName: `${apiName}.permissionset-meta.xml`,
      metadata: permSetMeta,
      category: 'admin',
    };
  }

  private createCodePermSet(
    profile: LoadedProfile,
    prefix: string,
    includeLicense?: boolean
  ): GeneratedPermissionSet | null {
    const meta = profile.metadata;
    const activeClasses = (meta.classAccesses || []).filter((c) => c.enabled);
    const activePages = (meta.pageAccesses || []).filter((p) => p.enabled);

    if (activeClasses.length === 0 && activePages.length === 0) return null;

    const apiName = `${prefix}Apex_Access`;
    const permSetMeta: PermissionSetMetadata = {
      label: `${this.formatLabel(profile.name)} - Apex & Visualforce Access`,
      description: `Apex class and Visualforce page execution permissions migrated from ${profile.name} by PermForge.`,
      hasActivationRequired: false,
      license: includeLicense ? profile.metadata.userLicense : undefined,
      classAccesses: activeClasses.length > 0 ? activeClasses : undefined,
      pageAccesses: activePages.length > 0 ? activePages : undefined,
    };

    return {
      apiName,
      fileName: `${apiName}.permissionset-meta.xml`,
      metadata: permSetMeta,
      category: 'apex',
    };
  }

  private createCustomPermSet(
    profile: LoadedProfile,
    prefix: string,
    includeLicense?: boolean
  ): GeneratedPermissionSet | null {
    const meta = profile.metadata;
    const activeCustom = (meta.customPermissions || []).filter((c) => c.enabled);
    if (activeCustom.length === 0) return null;

    const apiName = `${prefix}Custom_Permissions`;
    const permSetMeta: PermissionSetMetadata = {
      label: `${this.formatLabel(profile.name)} - Custom Permissions`,
      description: `Custom permissions migrated from profile ${profile.name} by PermForge.`,
      hasActivationRequired: false,
      license: includeLicense ? profile.metadata.userLicense : undefined,
      customPermissions: activeCustom,
    };

    return {
      apiName,
      fileName: `${apiName}.permissionset-meta.xml`,
      metadata: permSetMeta,
      category: 'custom',
    };
  }

  private async writeOutputs(
    outputDir: string,
    permSets: GeneratedPermissionSet[],
    psg?: GeneratedPermissionSetGroup
  ): Promise<void> {
    const permSetDir = path.join(outputDir, 'permissionsets');
    await fs.mkdir(permSetDir, { recursive: true });

    for (const ps of permSets) {
      const filePath = path.join(permSetDir, ps.fileName);
      const xml = this.xmlEngine.serializePermissionSet(ps.metadata);
      await fs.writeFile(filePath, xml, 'utf-8');
    }

    if (psg) {
      const psgDir = path.join(outputDir, 'permissionsetgroups');
      await fs.mkdir(psgDir, { recursive: true });
      const filePath = path.join(psgDir, psg.fileName);
      const xml = this.xmlEngine.serializePermissionSetGroup(psg.metadata);
      await fs.writeFile(filePath, xml, 'utf-8');
    }
  }

  private mapToDomain(sobjectName: string): string {
    const map: Record<string, string> = {
      Account: 'Account_Management',
      Contact: 'Account_Management',
      Lead: 'Sales_Lead',
      Opportunity: 'Sales_Opportunity',
      OpportunityLineItem: 'Sales_Opportunity',
      Case: 'Service_Case',
      CaseComment: 'Service_Case',
      Campaign: 'Marketing_Campaign',
      CampaignMember: 'Marketing_Campaign',
      Contract: 'Sales_Contract',
      Order: 'Sales_Order',
      OrderItem: 'Sales_Order',
      Product2: 'Product_Catalog',
      Pricebook2: 'Product_Catalog',
      PricebookEntry: 'Product_Catalog',
      Task: 'Activity_Management',
      Event: 'Activity_Management',
    };

    if (map[sobjectName]) return map[sobjectName];
    return sobjectName.replace(/__c$/, '').replace(/[^a-zA-Z0-9_]/g, '_');
  }

  private formatLabel(str: string): string {
    return str
      .replace(/_/g, ' ')
      .replace(/([A-Z])/g, ' $1')
      .replace(/\s+/g, ' ')
      .trim();
  }
}
