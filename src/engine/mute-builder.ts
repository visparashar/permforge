import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import { XMLBuilder } from 'fast-xml-parser';

export interface MuteObjectOptions {
  object: string;
  muteDelete?: boolean;
  muteEdit?: boolean;
  muteCreate?: boolean;
  muteRead?: boolean;
  muteViewAll?: boolean;
  muteModifyAll?: boolean;
}

export interface MuteFieldOptions {
  field: string;
  muteReadable?: boolean;
  muteEditable?: boolean;
}

export interface MuteOptions {
  name: string;
  label?: string;
  description?: string;
  mutedObjects?: MuteObjectOptions[];
  mutedFields?: MuteFieldOptions[];
  mutedUserPerms?: string[];
  outputDir: string;
}

export interface MuteResult {
  fileName: string;
  filePath: string;
  apiName: string;
}

export class MuteBuilder {
  private builder: XMLBuilder;

  constructor() {
    this.builder = new XMLBuilder({
      ignoreAttributes: false,
      attributeNamePrefix: '@_',
      format: true,
      indentBy: '    ',
      suppressEmptyNode: false,
    });
  }

  /**
   * Generate standard Salesforce MutingPermissionSet metadata.
   */
  public async generateMutingPermissionSet(options: MuteOptions): Promise<MuteResult> {
    const apiName = options.name.replace(/[^a-zA-Z0-9_]/g, '_');
    const label = options.label || apiName.replace(/_/g, ' ');
    const outputDir = path.resolve(options.outputDir, 'mutingpermissionsets');
    await fs.mkdir(outputDir, { recursive: true });

    const objPerms = (options.mutedObjects || []).map((o) => ({
      allowCreate: Boolean(o.muteCreate),
      allowDelete: o.muteDelete !== undefined ? Boolean(o.muteDelete) : true,
      allowEdit: Boolean(o.muteEdit),
      allowRead: Boolean(o.muteRead),
      modifyAllRecords: Boolean(o.muteModifyAll),
      object: o.object,
      viewAllRecords: Boolean(o.muteViewAll),
    }));

    const fieldPerms = (options.mutedFields || []).map((f) => ({
      editable: Boolean(f.muteEditable),
      field: f.field,
      readable: Boolean(f.muteReadable),
    }));

    const userPerms = (options.mutedUserPerms || []).map((p) => ({
      enabled: true,
      name: p,
    }));

    const mutingObj = {
      MutingPermissionSet: {
        '@_xmlns': 'http://soap.sforce.com/2006/04/metadata',
        description:
          options.description || `Muting Permission Set generated by PermForge for ${apiName}.`,
        hasActivationRequired: false,
        label,
        ...(fieldPerms.length > 0 ? { fieldPermissions: fieldPerms } : {}),
        ...(objPerms.length > 0 ? { objectPermissions: objPerms } : {}),
        ...(userPerms.length > 0 ? { userPermissions: userPerms } : {}),
      },
    };

    const xml = `<?xml version="1.0" encoding="UTF-8"?>\n${this.builder.build(mutingObj)}\n`;
    const fileName = `${apiName}.mutingpermissionset-meta.xml`;
    const filePath = path.join(outputDir, fileName);

    await fs.writeFile(filePath, xml, 'utf-8');

    return {
      fileName,
      filePath,
      apiName,
    };
  }
}
